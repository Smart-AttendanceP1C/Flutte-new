class AppLocalizationsDelegate extends LocalizationsDelegate<S> {
  const AppLocalizationsDelegate();

  @override
  bool isSupported(Locale locale) => S.supported.contains(locale.languageCode);

  @override
  Future<S> load(Locale locale) async => S();

  @override
  bool shouldReload(covariant LocalizationsDelegate<S> old) => false;
}

extension TrContext on BuildContext {
  String tr(String key, [Map<String, String>? args]) {
    var s = S.of(this, key);
    args?.forEach((k, v) => s = s.replaceAll('{$k}', v));
    return s;
  }
}
